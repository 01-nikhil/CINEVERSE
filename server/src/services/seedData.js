// Helper to generate dynamic showtimes for the next 7 days
export const generateShowtimes = () => {
  const showtimes = [];
  const times = ["10:30", "14:00", "17:30", "20:45", "23:15"];
  let idCounter = 1;

  const today = new Date();
  for (let i = 0; i < 7; i++) {
    const d = new Date(today);
    d.setDate(today.getDate() + i);
    const dateStr = d.toISOString().split('T')[0];

    sampleMovies.slice(0, 4).forEach((movie) => {
      sampleTheaters.forEach((theater) => {
        theater.screens.forEach((screen) => {
          times.slice(0, 3 + (theater.city === 'New York' ? 2 : 1)).forEach((time) => {
            // Generate some pre-booked sample seats
            const bookedSeats = [];
            if (i === 0) {
              const demoSeats = ["C5", "C6", "D5", "D6", "A3", "B7"];
              demoSeats.forEach((seat) => {
                bookedSeats.push({
                  seatNumber: seat,
                  status: 'booked'
                });
              });
            }

            showtimes.push({
              _id: `6620000000000000000000${(idCounter++).toString().padStart(4, '0')}`,
              movieId: movie._id,
              theaterId: theater._id,
              screenNumber: screen.screenNumber,
              screenType: screen.screenType,
              date: dateStr,
              time: time,
              prices: {
                vip: screen.screenType.includes('IMAX') ? 480 : 380,
                premium: screen.screenType.includes('IMAX') ? 340 : 280,
                standard: screen.screenType.includes('IMAX') ? 240 : 190,
              },
              bookedSeats: bookedSeats,
            });
          });
        });
      });
    });
  }
  return showtimes;
};

